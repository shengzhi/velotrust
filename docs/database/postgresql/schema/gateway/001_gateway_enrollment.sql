-- Management-owned gateway inventory and one-time registration credentials.
-- Credential plaintext is never persisted; only a SHA-256 digest is stored.

CREATE TABLE public.t_gateway_node (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gateway_id        VARCHAR(64) NOT NULL,
    gateway_name      VARCHAR(128) NOT NULL,
    gateway_type      VARCHAR(64) NOT NULL,
    network_name      VARCHAR(128) NOT NULL,
    allowed_subnets   JSONB NOT NULL DEFAULT '[]'::JSONB,
    require_approval  BOOLEAN NOT NULL DEFAULT TRUE,
    status            VARCHAR(32) NOT NULL DEFAULT 'pending_enrollment',
    registered_at     TIMESTAMPTZ,
    created_by        BIGINT NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version_no        BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT uq_t_gateway_node_gateway_id UNIQUE (gateway_id),
    CONSTRAINT uq_t_gateway_node_name UNIQUE (gateway_name),
    CONSTRAINT fk_t_gateway_node_creator FOREIGN KEY (created_by)
        REFERENCES public.t_iam_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_gateway_node_subnets CHECK (
        jsonb_typeof(allowed_subnets) = 'array' AND jsonb_array_length(allowed_subnets) BETWEEN 1 AND 32
    ),
    CONSTRAINT ck_t_gateway_node_status CHECK (
        status IN ('pending_enrollment', 'registered', 'suspended', 'revoked')
    ),
    CONSTRAINT ck_t_gateway_node_version CHECK (version_no > 0)
);

CREATE INDEX ix_t_gateway_node_status_created ON public.t_gateway_node (status, created_at DESC);
CREATE INDEX ix_t_gateway_node_network ON public.t_gateway_node (network_name, status);

CREATE TABLE public.t_gateway_registration_token (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gateway_row_id      BIGINT NOT NULL,
    token_hash          CHAR(64) NOT NULL,
    status              VARCHAR(16) NOT NULL DEFAULT 'pending',
    max_uses            SMALLINT NOT NULL DEFAULT 1,
    used_count          SMALLINT NOT NULL DEFAULT 0,
    expires_at          TIMESTAMPTZ NOT NULL,
    notes               VARCHAR(512),
    created_by          BIGINT NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    used_at             TIMESTAMPTZ,
    used_ip             INET,
    revoked_at          TIMESTAMPTZ,
    revocation_reason   VARCHAR(512),
    CONSTRAINT uq_t_gateway_registration_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_t_gateway_registration_gateway FOREIGN KEY (gateway_row_id)
        REFERENCES public.t_gateway_node (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_gateway_registration_creator FOREIGN KEY (created_by)
        REFERENCES public.t_iam_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_gateway_registration_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_t_gateway_registration_status CHECK (status IN ('pending', 'used', 'expired', 'revoked')),
    CONSTRAINT ck_t_gateway_registration_uses CHECK (max_uses = 1 AND used_count BETWEEN 0 AND max_uses)
);

CREATE UNIQUE INDEX uq_t_gateway_registration_pending_gateway
    ON public.t_gateway_registration_token (gateway_row_id) WHERE status = 'pending';
CREATE INDEX ix_t_gateway_registration_status_expiry
    ON public.t_gateway_registration_token (status, expires_at);
CREATE INDEX ix_t_gateway_registration_gateway_created
    ON public.t_gateway_registration_token (gateway_row_id, created_at DESC);

COMMENT ON TABLE public.t_gateway_registration_token IS
    'Single-use gateway enrollment credentials. Stores only SHA-256 digests; plaintext is returned only at issuance.';
COMMENT ON COLUMN public.t_gateway_registration_token.token_hash IS
    'Lowercase SHA-256 hex digest of the one-time credential; never store or audit the plaintext.';
