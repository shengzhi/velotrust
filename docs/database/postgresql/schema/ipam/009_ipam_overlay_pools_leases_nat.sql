-- Persistent Overlay address pools, address leases, and enterprise NAT mappings.

CREATE TABLE public.t_ztna_address_pool (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_name         VARCHAR(128) NOT NULL,
    network_cidr      CIDR NOT NULL,
    pool_type         VARCHAR(32) NOT NULL,
    allocation_mode   VARCHAR(16) NOT NULL,
    idp_group         VARCHAR(128),
    gateway_binding   VARCHAR(128),
    color             CHAR(7) NOT NULL DEFAULT '#10b981',
    description       VARCHAR(512),
    status            VARCHAR(16) NOT NULL DEFAULT 'active',
    created_by        BIGINT NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version_no        BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT uq_t_ztna_address_pool_name UNIQUE (pool_name),
    CONSTRAINT ck_t_ztna_address_pool_type CHECK (pool_type IN ('Gateway', 'User-Device', 'Service-VIP')),
    CONSTRAINT ck_t_ztna_address_pool_allocation CHECK (allocation_mode IN ('static', 'dynamic')),
    CONSTRAINT ck_t_ztna_address_pool_color CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
    CONSTRAINT ck_t_ztna_address_pool_status CHECK (status IN ('active', 'disabled')),
    CONSTRAINT ck_t_ztna_address_pool_not_default CHECK (network_cidr <> '0.0.0.0/0'::cidr AND network_cidr <> '::/0'::cidr),
    CONSTRAINT ck_t_ztna_address_pool_version CHECK (version_no > 0),
    CONSTRAINT fk_t_ztna_address_pool_creator FOREIGN KEY (created_by)
        REFERENCES public.t_iam_user (id) ON DELETE RESTRICT
);

CREATE INDEX ix_t_ztna_address_pool_status ON public.t_ztna_address_pool (status, pool_name);
CREATE INDEX ix_t_ztna_address_pool_cidr ON public.t_ztna_address_pool (network_cidr);

CREATE TABLE public.t_ztna_address_lease (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool_id             BIGINT NOT NULL,
    address             INET NOT NULL,
    node_type           VARCHAR(16) NOT NULL,
    target_name         VARCHAR(128) NOT NULL,
    endpoint            VARCHAR(255),
    allocation_mode     VARCHAR(64) NOT NULL,
    idp_group           VARCHAR(128),
    wireguard_pubkey    VARCHAR(64),
    status              VARCHAR(16) NOT NULL DEFAULT 'active',
    allocated_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_at         TIMESTAMPTZ,
    created_by          BIGINT NOT NULL,
    CONSTRAINT ck_t_ztna_address_lease_node_type CHECK (node_type IN ('Gateway', 'Peer', 'Server')),
    CONSTRAINT ck_t_ztna_address_lease_status CHECK (status IN ('active', 'reserved', 'released')),
    CONSTRAINT ck_t_ztna_address_lease_pubkey CHECK (wireguard_pubkey IS NULL OR length(wireguard_pubkey) = 44),
    CONSTRAINT ck_t_ztna_address_lease_release CHECK ((status = 'released') = (released_at IS NOT NULL)),
    CONSTRAINT fk_t_ztna_address_lease_pool FOREIGN KEY (pool_id)
        REFERENCES public.t_ztna_address_pool (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_address_lease_creator FOREIGN KEY (created_by)
        REFERENCES public.t_iam_user (id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_t_ztna_address_lease_active_address
    ON public.t_ztna_address_lease (address) WHERE status IN ('active', 'reserved');
CREATE UNIQUE INDEX uq_t_ztna_address_lease_active_target
    ON public.t_ztna_address_lease (pool_id, target_name) WHERE status IN ('active', 'reserved');
CREATE UNIQUE INDEX uq_t_ztna_address_lease_active_pubkey
    ON public.t_ztna_address_lease (wireguard_pubkey)
    WHERE status IN ('active', 'reserved') AND wireguard_pubkey IS NOT NULL;
CREATE INDEX ix_t_ztna_address_lease_pool_status ON public.t_ztna_address_lease (pool_id, status, allocated_at DESC);

CREATE TABLE public.t_ztna_nat_mapping (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_id       BIGINT NOT NULL,
    network_name     VARCHAR(128) NOT NULL,
    real_cidr        CIDR NOT NULL,
    virtual_cidr     CIDR,
    nat_type         VARCHAR(32) NOT NULL,
    enabled          BOOLEAN NOT NULL DEFAULT TRUE,
    description      VARCHAR(512),
    created_by       BIGINT NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version_no       BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT uq_t_ztna_nat_mapping_network UNIQUE (network_id),
    CONSTRAINT ck_t_ztna_nat_mapping_type CHECK (nat_type IN ('1:1_Bidirectional', 'SNAT_Masquerade', 'DNAT_VirtualIP')),
    CONSTRAINT ck_t_ztna_nat_mapping_virtual_required CHECK (nat_type = 'SNAT_Masquerade' OR virtual_cidr IS NOT NULL),
    CONSTRAINT ck_t_ztna_nat_mapping_version CHECK (version_no > 0),
    CONSTRAINT fk_t_ztna_nat_mapping_network FOREIGN KEY (network_id)
        REFERENCES public.t_ztna_network (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_nat_mapping_creator FOREIGN KEY (created_by)
        REFERENCES public.t_iam_user (id) ON DELETE RESTRICT
);

CREATE INDEX ix_t_ztna_nat_mapping_enabled ON public.t_ztna_nat_mapping (enabled, network_id);
CREATE INDEX ix_t_ztna_nat_mapping_virtual ON public.t_ztna_nat_mapping (virtual_cidr);

COMMENT ON TABLE public.t_ztna_address_pool IS
    'WireGuard overlay IPv4 address pools. These are separate from routed enterprise networks in t_ztna_network.';
COMMENT ON TABLE public.t_ztna_address_lease IS
    'Allocated overlay addresses. Released leases remain as history; only active/reserved addresses occupy an IP.';
COMMENT ON TABLE public.t_ztna_nat_mapping IS
    'Persistent NAT mapping inventory for enterprise networks. A management record is not proof of Gateway dataplane application.';
