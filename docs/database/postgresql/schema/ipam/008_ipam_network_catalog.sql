-- Persist enterprise networks and gateway-to-network selections.
-- These are routed business networks, separate from WireGuard overlay pools.

CREATE TABLE public.t_ztna_network (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    network_name   VARCHAR(128) NOT NULL,
    network_code   VARCHAR(64) NOT NULL,
    network_type   VARCHAR(32) NOT NULL,
    cidr           CIDR NOT NULL,
    region         VARCHAR(128),
    environment    VARCHAR(32),
    description    VARCHAR(512),
    status         VARCHAR(24) NOT NULL DEFAULT 'active',
    created_by     BIGINT NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version_no     BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT uq_t_ztna_network_code UNIQUE (network_code),
    CONSTRAINT ck_t_ztna_network_code CHECK (network_code ~ '^[a-z0-9][a-z0-9._-]{1,63}$'),
    CONSTRAINT ck_t_ztna_network_type CHECK (network_type IN ('vpc', 'subnet', 'site', 'segment')),
    CONSTRAINT ck_t_ztna_network_not_default CHECK (cidr <> '0.0.0.0/0'::cidr AND cidr <> '::/0'::cidr),
    CONSTRAINT ck_t_ztna_network_status CHECK (status IN ('active', 'disabled')),
    CONSTRAINT ck_t_ztna_network_version CHECK (version_no > 0),
    CONSTRAINT fk_t_ztna_network_creator FOREIGN KEY (created_by)
        REFERENCES public.t_iam_user (id) ON DELETE RESTRICT
);

CREATE INDEX ix_t_ztna_network_status_type ON public.t_ztna_network (status, network_type, network_name);
CREATE INDEX ix_t_ztna_network_cidr ON public.t_ztna_network (cidr);

CREATE TABLE public.t_gateway_node_network (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gateway_row_id  BIGINT NOT NULL,
    network_id      BIGINT NOT NULL,
    network_name    VARCHAR(128) NOT NULL,
    allowed_cidr    CIDR NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_t_gateway_node_network UNIQUE (gateway_row_id, network_id),
    CONSTRAINT fk_t_gateway_node_network_gateway FOREIGN KEY (gateway_row_id)
        REFERENCES public.t_gateway_node (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_gateway_node_network_network FOREIGN KEY (network_id)
        REFERENCES public.t_ztna_network (id) ON DELETE RESTRICT
);

CREATE INDEX ix_t_gateway_node_network_network ON public.t_gateway_node_network (network_id);

INSERT INTO public.t_iam_resource
    (resource_name, resource_code, resource_type, description, status, created_by, updated_by)
VALUES
    ('IPAM 网络目录', 'ipam.network', 'management', '管理企业业务网络与可路由网段', 'active', 'migration', 'migration')
ON CONFLICT (resource_code) DO UPDATE SET
    resource_name = EXCLUDED.resource_name,
    resource_type = EXCLUDED.resource_type,
    description = EXCLUDED.description,
    status = 'active',
    updated_at = CURRENT_TIMESTAMP,
    updated_by = 'migration',
    version_no = public.t_iam_resource.version_no + 1;

INSERT INTO public.t_iam_permission
    (permission_name, permission_code, resource_id, action_code, description, status, created_by, updated_by)
SELECT seed.permission_name, seed.permission_code, resource.id, seed.action_code, seed.description,
       'active', 'migration', 'migration'
FROM public.t_iam_resource resource
CROSS JOIN (VALUES
    ('查看 IPAM 网络', 'ipam.network.read', 'read', '查看企业业务网络和可路由网段'),
    ('管理 IPAM 网络', 'ipam.network.write', 'write', '新增或停用企业业务网络')
) AS seed(permission_name, permission_code, action_code, description)
WHERE resource.resource_code = 'ipam.network'
ON CONFLICT (permission_code) DO UPDATE SET
    permission_name = EXCLUDED.permission_name,
    resource_id = EXCLUDED.resource_id,
    action_code = EXCLUDED.action_code,
    description = EXCLUDED.description,
    status = 'active',
    updated_at = CURRENT_TIMESTAMP,
    updated_by = 'migration',
    version_no = public.t_iam_permission.version_no + 1;

INSERT INTO public.t_iam_role_permission (role_id, permission_id, created_by)
SELECT role.id, permission.id, 'migration'
FROM public.t_iam_role role
CROSS JOIN public.t_iam_permission permission
WHERE role.role_code = 'platform_admin'
  AND role.status = 'active'
  AND permission.permission_code IN ('ipam.network.read', 'ipam.network.write')
ON CONFLICT (role_id, permission_id) DO NOTHING;
