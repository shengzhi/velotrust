-- Durable authorization-change fanout from Management to connected Gateways.
-- The migration runner owns the transaction.

ALTER TABLE public.t_ztna_device
    ADD COLUMN node_id BIGINT;

ALTER TABLE public.t_ztna_device
    ADD CONSTRAINT fk_t_ztna_device_node
        FOREIGN KEY (node_id) REFERENCES public.t_ztna_node (id) ON DELETE RESTRICT;

-- Attach only unambiguous credential matches. Ambiguous legacy
-- credentials remain unlinked and can be resolved from the device screen.
WITH matches AS (
    SELECT DISTINCT credential.device_id, node.id AS node_id
    FROM public.t_ztna_device_credential AS credential
    JOIN public.t_ztna_node AS node ON node.public_key = credential.public_key
    WHERE node.node_type = 'client_agent'
      AND node.node_status <> 'revoked'
), counted_matches AS (
    SELECT device_id, node_id,
           COUNT(*) OVER (PARTITION BY device_id) AS device_match_count,
           COUNT(*) OVER (PARTITION BY node_id) AS node_match_count
    FROM matches
), unambiguous AS (
    SELECT device_id, MIN(node_id) AS node_id
    FROM counted_matches
    WHERE device_match_count = 1 AND node_match_count = 1
    GROUP BY device_id
)
UPDATE public.t_ztna_device AS device
SET node_id = unambiguous.node_id
FROM unambiguous
WHERE device.id = unambiguous.device_id;

CREATE UNIQUE INDEX uq_t_ztna_device_node
    ON public.t_ztna_device (node_id) WHERE node_id IS NOT NULL;

CREATE TABLE public.t_ztna_access_change_event (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type        VARCHAR(24) NOT NULL,
    subject_id          BIGINT NOT NULL,
    change_type         VARCHAR(32) NOT NULL,
    status              VARCHAR(16) NOT NULL DEFAULT 'pending',
    targets_initialized BOOLEAN NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by          VARCHAR(64) NOT NULL DEFAULT '',
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by          VARCHAR(64) NOT NULL DEFAULT '',
    version_no          BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT ck_t_ztna_access_change_subject CHECK (subject_type IN ('user', 'device', 'node')),
    CONSTRAINT ck_t_ztna_access_change_type CHECK (change_type IN ('disabled', 'enabled', 'authorization_changed')),
    CONSTRAINT ck_t_ztna_access_change_status CHECK (status IN ('pending', 'completed')),
    CONSTRAINT ck_t_ztna_access_change_version CHECK (version_no > 0)
);

CREATE INDEX ix_t_ztna_access_change_pending
    ON public.t_ztna_access_change_event (status, created_at, id);
CREATE INDEX ix_t_ztna_access_change_subject
    ON public.t_ztna_access_change_event (subject_type, subject_id, created_at DESC);

CREATE TABLE public.t_ztna_access_change_delivery (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id            BIGINT NOT NULL,
    gateway_node_id     BIGINT NOT NULL,
    status              VARCHAR(16) NOT NULL DEFAULT 'pending',
    last_notified_at    TIMESTAMPTZ,
    acknowledged_at     TIMESTAMPTZ,
    last_error          VARCHAR(512),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by          VARCHAR(64) NOT NULL DEFAULT '',
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by          VARCHAR(64) NOT NULL DEFAULT '',
    version_no          BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT fk_t_ztna_access_change_delivery_event FOREIGN KEY (event_id)
        REFERENCES public.t_ztna_access_change_event (id) ON DELETE CASCADE,
    CONSTRAINT fk_t_ztna_access_change_delivery_gateway FOREIGN KEY (gateway_node_id)
        REFERENCES public.t_ztna_node (id) ON DELETE RESTRICT,
    CONSTRAINT uq_t_ztna_access_change_delivery_target UNIQUE (event_id, gateway_node_id),
    CONSTRAINT ck_t_ztna_access_change_delivery_status CHECK (status IN ('pending', 'acknowledged')),
    CONSTRAINT ck_t_ztna_access_change_delivery_ack CHECK ((status = 'acknowledged') = (acknowledged_at IS NOT NULL)),
    CONSTRAINT ck_t_ztna_access_change_delivery_version CHECK (version_no > 0)
);

CREATE INDEX ix_t_ztna_access_change_delivery_pending
    ON public.t_ztna_access_change_delivery (gateway_node_id, status, last_notified_at);
