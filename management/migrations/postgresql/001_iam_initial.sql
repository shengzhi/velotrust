-- VeloTrust IAM baseline schema for PostgreSQL.
-- Source model: docs/VeloTrust_数据模型设计文档_最终版.md
-- IAM design: docs/VeloTrust_IAM身份与访问管理模块设计.md
--
-- Initial PostgreSQL schema migration. The migration runner wraps this file
-- in a transaction and records its checksum in the migration history table.
-- All timestamps are timestamptz and should be written in UTC by the app.


-- ---------------------------------------------------------------------------
-- Users, groups, and roles
-- ---------------------------------------------------------------------------

CREATE TABLE public.t_iam_user (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username              VARCHAR(64) NOT NULL,
    display_name          VARCHAR(128) NOT NULL DEFAULT '',
    email                 VARCHAR(128),
    phone_country_code    VARCHAR(8),
    phone_number          VARCHAR(32),
    webauthn_user_handle  BYTEA,
    password_salt         VARCHAR(64),
    password_hash         VARCHAR(255),
    password_hash_version SMALLINT,
    auth_source           VARCHAR(32) NOT NULL DEFAULT 'local',
    user_status           VARCHAR(24) NOT NULL DEFAULT 'pending',
    must_change_password  BOOLEAN NOT NULL DEFAULT FALSE,
    last_login_at         TIMESTAMPTZ,
    last_login_ip         VARCHAR(64),
    remark                VARCHAR(512),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by            VARCHAR(64) NOT NULL DEFAULT '',
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by            VARCHAR(64) NOT NULL DEFAULT '',
    version_no            BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT ck_t_iam_user_auth_source
        CHECK (auth_source IN ('local', 'external', 'mixed')),
    CONSTRAINT ck_t_iam_user_status
        CHECK (user_status IN ('active', 'disabled', 'locked', 'pending')),
    CONSTRAINT ck_t_iam_user_password_fields
        CHECK (
            (password_hash IS NULL AND password_salt IS NULL AND password_hash_version IS NULL)
            OR
            (password_hash IS NOT NULL AND password_salt IS NOT NULL AND password_hash_version IS NOT NULL)
        ),
    CONSTRAINT uq_t_iam_user_webauthn_user_handle UNIQUE (webauthn_user_handle),
    CONSTRAINT ck_t_iam_user_webauthn_user_handle
        CHECK (webauthn_user_handle IS NULL OR octet_length(webauthn_user_handle) BETWEEN 1 AND 64),
    CONSTRAINT ck_t_iam_user_version_no CHECK (version_no > 0)
);

-- Usernames are canonicalized by the application; this index also prevents
-- case-only duplicates in PostgreSQL.
CREATE UNIQUE INDEX uq_t_iam_user_username_ci ON public.t_iam_user (LOWER(username));
CREATE INDEX ix_t_iam_user_status ON public.t_iam_user (user_status);
CREATE INDEX ix_t_iam_user_email_ci ON public.t_iam_user (LOWER(email)) WHERE email IS NOT NULL;
CREATE INDEX ix_t_iam_user_last_login_at ON public.t_iam_user (last_login_at);

COMMENT ON TABLE public.t_iam_user IS
    'Unified internal identity for administrators and employees. User deletion should normally be logical disablement.';
COMMENT ON COLUMN public.t_iam_user.password_salt IS
    'Per-user random salt for the configured password KDF; never return through ordinary APIs.';
COMMENT ON COLUMN public.t_iam_user.password_hash IS
    'Password KDF output only; never store plaintext. Algorithm parameters are selected by password_hash_version.';
COMMENT ON COLUMN public.t_iam_user.password_hash_version IS
    'Versioned Argon2id parameter set; increment when KDF parameters change.';
COMMENT ON COLUMN public.t_iam_user.webauthn_user_handle IS
    'Random opaque WebAuthn user handle, at most 64 bytes; do not derive it from the database user ID.';

