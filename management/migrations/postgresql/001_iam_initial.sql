-- Shared across Management replicas. Store HMACs of normalized account/IP keys,
-- never raw usernames or raw address values in this throttle table.
CREATE TABLE public.t_iam_auth_throttle (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket_key_hash  CHAR(64) NOT NULL,
    dimension        VARCHAR(24) NOT NULL,
    window_started_at TIMESTAMPTZ NOT NULL,
    failure_count    INTEGER NOT NULL DEFAULT 0,
    blocked_until    TIMESTAMPTZ,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_t_iam_auth_throttle_bucket
        UNIQUE (dimension, bucket_key_hash, window_started_at),
    CONSTRAINT ck_t_iam_auth_throttle_dimension
        CHECK (dimension IN ('username', 'source_ip')),
    CONSTRAINT ck_t_iam_auth_throttle_hash
        CHECK (bucket_key_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_t_iam_auth_throttle_failure_count CHECK (failure_count >= 0)
);

CREATE INDEX ix_t_iam_auth_throttle_blocked_until
    ON public.t_iam_auth_throttle (blocked_until) WHERE blocked_until IS NOT NULL;
CREATE INDEX ix_t_iam_auth_throttle_window
    ON public.t_iam_auth_throttle (window_started_at);

COMMENT ON TABLE public.t_iam_auth_throttle IS
    'Atomic shared login throttling state. Expired rows should be pruned by a bounded maintenance job.';

