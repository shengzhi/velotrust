    CONSTRAINT ck_t_iam_rpc_method_version_no CHECK (version_no > 0)
);

CREATE UNIQUE INDEX uq_t_iam_rpc_method_http_route
    ON public.t_iam_rpc_method (http_method, path_pattern) WHERE protocol = 'http';
