-- WebAuthn/FIDO2 passkey public credentials. The authenticator private key is
-- never sent to or stored by VeloTrust.
CREATE TABLE public.t_iam_webauthn_credential (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT NOT NULL,
    rp_id             VARCHAR(255) NOT NULL,
    credential_id     BYTEA NOT NULL,
    public_key_cose   BYTEA NOT NULL,
    signature_count   BIGINT NOT NULL DEFAULT 0,
    aaguid            BYTEA,
    transports        JSONB NOT NULL DEFAULT '[]'::JSONB,
    backup_eligible   BOOLEAN NOT NULL DEFAULT FALSE,
    backup_state      BOOLEAN NOT NULL DEFAULT FALSE,
    credential_name   VARCHAR(128) NOT NULL DEFAULT '',
    status            VARCHAR(24) NOT NULL DEFAULT 'active',
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at      TIMESTAMPTZ,
    revoked_at        TIMESTAMPTZ,
    revocation_reason VARCHAR(128),
    CONSTRAINT uq_t_iam_webauthn_rp_credential UNIQUE (rp_id, credential_id),
    CONSTRAINT fk_t_iam_webauthn_credential_user FOREIGN KEY (user_id)
        REFERENCES public.t_iam_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_iam_webauthn_credential_id_length
        CHECK (octet_length(credential_id) BETWEEN 1 AND 1023),
    CONSTRAINT ck_t_iam_webauthn_public_key_length
        CHECK (octet_length(public_key_cose) > 0),
    CONSTRAINT ck_t_iam_webauthn_signature_count
        CHECK (signature_count BETWEEN 0 AND 4294967295),
    CONSTRAINT ck_t_iam_webauthn_aaguid
        CHECK (aaguid IS NULL OR octet_length(aaguid) = 16),
    CONSTRAINT ck_t_iam_webauthn_transports
        CHECK (jsonb_typeof(transports) = 'array'),
    CONSTRAINT ck_t_iam_webauthn_backup_state
        CHECK (NOT backup_state OR backup_eligible),
    CONSTRAINT ck_t_iam_webauthn_status
        CHECK (status IN ('active', 'disabled', 'revoked')),
    CONSTRAINT ck_t_iam_webauthn_revocation
        CHECK (
            (status = 'revoked' AND revoked_at IS NOT NULL)
            OR (status <> 'revoked' AND revoked_at IS NULL)
        )
);

CREATE INDEX ix_t_iam_webauthn_user_status
    ON public.t_iam_webauthn_credential (user_id, status);
CREATE INDEX ix_t_iam_webauthn_rp_status
    ON public.t_iam_webauthn_credential (rp_id, status);

COMMENT ON TABLE public.t_iam_webauthn_credential IS
    'WebAuthn passkey credential metadata and public key only; authenticator private keys remain with the authenticator.';
COMMENT ON COLUMN public.t_iam_webauthn_credential.signature_count IS
    'Authenticator signature counter; treat as a risk signal because some synced credentials do not provide a monotonic counter.';
COMMENT ON COLUMN public.t_iam_webauthn_credential.backup_eligible IS
    'WebAuthn BE flag captured at registration; indicates whether the credential can be backed up/synced.';
COMMENT ON COLUMN public.t_iam_webauthn_credential.backup_state IS
    'WebAuthn BS flag from the latest verified assertion.';

