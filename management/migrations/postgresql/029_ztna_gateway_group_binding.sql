-- Gateway tunnel admission is granted to employee security groups. Resource
-- access behind the Gateway continues to be controlled by ZTNA policies.
BEGIN;

CREATE TABLE public.t_ztna_gateway_group_binding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gateway_node_id BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64) NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(64) NOT NULL DEFAULT '',
    version_no BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT uq_t_ztna_gateway_group_binding UNIQUE (gateway_node_id, group_id),
    CONSTRAINT fk_t_ztna_gateway_group_binding_node
        FOREIGN KEY (gateway_node_id) REFERENCES public.t_ztna_node (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_gateway_group_binding_group
        FOREIGN KEY (group_id) REFERENCES public.t_iam_group (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_ztna_gateway_group_binding_version CHECK (version_no > 0)
);

CREATE INDEX ix_t_ztna_gateway_group_binding_group
    ON public.t_ztna_gateway_group_binding (group_id, gateway_node_id);

COMMIT;
