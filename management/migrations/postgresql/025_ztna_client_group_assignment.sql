-- Map each active employee group to one Client tunnel and dynamic address pool.
-- The HUB consumes this mapping during Client enrollment and reconciliation.

CREATE TABLE public.t_ztna_client_group_assignment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id    BIGINT NOT NULL,
    tunnel_id   BIGINT NOT NULL,
    pool_id     BIGINT NOT NULL,
    status      VARCHAR(16) NOT NULL DEFAULT 'active',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by  VARCHAR(64) NOT NULL DEFAULT '',
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by  VARCHAR(64) NOT NULL DEFAULT '',
    version_no  BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT uq_t_ztna_client_group_assignment_group UNIQUE (group_id),
    CONSTRAINT fk_t_ztna_client_group_assignment_group FOREIGN KEY (group_id)
        REFERENCES public.t_iam_group (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_client_group_assignment_tunnel FOREIGN KEY (tunnel_id)
        REFERENCES public.t_ztna_tunnel (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_client_group_assignment_pool FOREIGN KEY (pool_id)
        REFERENCES public.t_ztna_address_pool (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_ztna_client_group_assignment_status CHECK (status IN ('active', 'disabled')),
    CONSTRAINT ck_t_ztna_client_group_assignment_version CHECK (version_no > 0)
);

CREATE INDEX ix_t_ztna_client_group_assignment_status
    ON public.t_ztna_client_group_assignment (status, group_id);

COMMENT ON TABLE public.t_ztna_client_group_assignment IS
    'Selects the logical tunnel and dynamic User-Device pool for Clients in an IAM group.';
