-- One-time Client Agent enrollment credentials. The node, device, and owner
-- are created by Management; HUB consumes this credential and binds the
-- proved X25519 public key.

CREATE TABLE public.t_ztna_client_registration_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id     BIGINT NOT NULL,
    device_id   BIGINT NOT NULL,
    token_hash  VARCHAR(64) NOT NULL,
    status      VARCHAR(16) NOT NULL DEFAULT 'pending',
    max_uses    INTEGER NOT NULL DEFAULT 1,
    used_count  INTEGER NOT NULL DEFAULT 0,
    expires_at  TIMESTAMPTZ NOT NULL,
    notes       VARCHAR(512),
    used_at     TIMESTAMPTZ,
    used_ip     INET,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by  VARCHAR(64) NOT NULL DEFAULT '',
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by  VARCHAR(64) NOT NULL DEFAULT '',
    version_no  BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT uq_t_ztna_client_registration_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_t_ztna_client_registration_node FOREIGN KEY (node_id)
        REFERENCES public.t_ztna_node (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_client_registration_device FOREIGN KEY (device_id)
        REFERENCES public.t_ztna_device (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_ztna_client_registration_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_t_ztna_client_registration_status CHECK (status IN ('pending', 'used', 'expired', 'revoked')),
    CONSTRAINT ck_t_ztna_client_registration_uses CHECK (max_uses = 1 AND used_count BETWEEN 0 AND max_uses),
    CONSTRAINT ck_t_ztna_client_registration_version CHECK (version_no > 0)
);

CREATE UNIQUE INDEX uq_t_ztna_client_registration_pending_node
    ON public.t_ztna_client_registration_token (node_id) WHERE status = 'pending';
CREATE INDEX ix_t_ztna_client_registration_status_expiry
    ON public.t_ztna_client_registration_token (status, expires_at);

COMMENT ON TABLE public.t_ztna_client_registration_token IS
    'One-time, owner-bound Client Agent enrollment credentials consumed by HUB after X25519 proof.';
