-- Core VeloTrust ZTNA business schema based on
-- docs/VeloTrust_数据模型设计文档_最终版.md.
-- IAM, t_ztna_network, gateway enrollment, and IPAM tables are created by
-- earlier migrations and are intentionally not duplicated here.

-- ---------------------------------------------------------------------------
-- Device identity and posture
-- ---------------------------------------------------------------------------

CREATE TABLE public.t_ztna_device (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_name    VARCHAR(128) NOT NULL,
    device_uuid    VARCHAR(128) NOT NULL,
    device_type    VARCHAR(32) NOT NULL,
    platform       VARCHAR(64) NOT NULL,
    platform_version VARCHAR(128),
    agent_version  VARCHAR(64),
    owner_user_id  BIGINT,
    status         VARCHAR(24) NOT NULL DEFAULT 'pending',
    trust_status   VARCHAR(24) NOT NULL DEFAULT 'unknown',
    last_seen_at   TIMESTAMPTZ,
    last_seen_ip   INET,
    posture_json   JSONB,
    registered_at  TIMESTAMPTZ,
    revoked_at     TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by     VARCHAR(64) NOT NULL DEFAULT '',
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by     VARCHAR(64) NOT NULL DEFAULT '',
    version_no     BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT uq_t_ztna_device_uuid UNIQUE (device_uuid),
    CONSTRAINT fk_t_ztna_device_owner FOREIGN KEY (owner_user_id)
        REFERENCES public.t_iam_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_ztna_device_status CHECK (status IN ('pending', 'active', 'disabled', 'quarantined', 'revoked')),
    CONSTRAINT ck_t_ztna_device_trust CHECK (trust_status IN ('unknown', 'trusted', 'untrusted', 'review_required')),
    CONSTRAINT ck_t_ztna_device_posture_json CHECK (posture_json IS NULL OR jsonb_typeof(posture_json) = 'object'),
    CONSTRAINT ck_t_ztna_device_revoked CHECK ((status = 'revoked') = (revoked_at IS NOT NULL)),
    CONSTRAINT ck_t_ztna_device_version CHECK (version_no > 0)
);

CREATE INDEX ix_t_ztna_device_owner_status ON public.t_ztna_device (owner_user_id, status);
CREATE INDEX ix_t_ztna_device_trust_status ON public.t_ztna_device (trust_status, status);
CREATE INDEX ix_t_ztna_device_last_seen ON public.t_ztna_device (last_seen_at DESC);

CREATE TABLE public.t_ztna_device_credential (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id         BIGINT NOT NULL,
    credential_type   VARCHAR(32) NOT NULL,
    public_key        VARCHAR(512) NOT NULL,
    fingerprint       VARCHAR(128) NOT NULL,
    key_version       INTEGER NOT NULL DEFAULT 1,
    status            VARCHAR(16) NOT NULL DEFAULT 'active',
    not_before        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at        TIMESTAMPTZ,
    revoked_at        TIMESTAMPTZ,
    revocation_reason VARCHAR(512),
    last_used_at      TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by        VARCHAR(64) NOT NULL DEFAULT '',
    CONSTRAINT uq_t_ztna_device_credential_version UNIQUE (device_id, credential_type, key_version),
    CONSTRAINT fk_t_ztna_device_credential_device FOREIGN KEY (device_id)
        REFERENCES public.t_ztna_device (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_ztna_device_credential_status CHECK (status IN ('active', 'revoked', 'expired')),
    CONSTRAINT ck_t_ztna_device_credential_version CHECK (key_version > 0),
    CONSTRAINT ck_t_ztna_device_credential_expiry CHECK (expires_at IS NULL OR expires_at > not_before),
    CONSTRAINT ck_t_ztna_device_credential_revoked CHECK ((status = 'revoked') = (revoked_at IS NOT NULL))
);

CREATE UNIQUE INDEX uq_t_ztna_device_credential_fingerprint
    ON public.t_ztna_device_credential (fingerprint);
CREATE INDEX ix_t_ztna_device_credential_device_status
    ON public.t_ztna_device_credential (device_id, status, expires_at);

CREATE TABLE public.t_ztna_device_posture_check (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id     BIGINT NOT NULL,
    check_type    VARCHAR(64) NOT NULL,
    result        VARCHAR(16) NOT NULL,
    reason_code   VARCHAR(128),
    details_json  JSONB NOT NULL DEFAULT '{}'::JSONB,
    checked_at    TIMESTAMPTZ NOT NULL,
    valid_until   TIMESTAMPTZ,
    policy_version BIGINT,
    CONSTRAINT fk_t_ztna_device_posture_device FOREIGN KEY (device_id)
        REFERENCES public.t_ztna_device (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_ztna_device_posture_result CHECK (result IN ('pass', 'fail', 'warn', 'error')),
    CONSTRAINT ck_t_ztna_device_posture_details CHECK (jsonb_typeof(details_json) = 'object'),
    CONSTRAINT ck_t_ztna_device_posture_validity CHECK (valid_until IS NULL OR valid_until > checked_at),
    CONSTRAINT ck_t_ztna_device_posture_policy_version CHECK (policy_version IS NULL OR policy_version > 0)
);

CREATE INDEX ix_t_ztna_device_posture_device_checked
    ON public.t_ztna_device_posture_check (device_id, checked_at DESC);
CREATE INDEX ix_t_ztna_device_posture_result_validity
    ON public.t_ztna_device_posture_check (result, valid_until);

-- ---------------------------------------------------------------------------
-- Managed nodes and protected resources
-- ---------------------------------------------------------------------------

CREATE TABLE public.t_ztna_node (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_name             VARCHAR(128) NOT NULL,
    node_code             VARCHAR(64) NOT NULL,
    node_type             VARCHAR(32) NOT NULL,
    node_status           VARCHAR(24) NOT NULL DEFAULT 'pending',
    agent_version         VARCHAR(64),
    control_endpoint      VARCHAR(255),
    public_endpoint       VARCHAR(255),
    private_endpoint      VARCHAR(255),
    public_key            VARCHAR(64),
    last_heartbeat_at     TIMESTAMPTZ,
    last_config_version   BIGINT NOT NULL DEFAULT 0,
    actual_config_version BIGINT NOT NULL DEFAULT 0,
    capabilities_json     JSONB NOT NULL DEFAULT '{}'::JSONB,
    health_status         VARCHAR(24) NOT NULL DEFAULT 'unknown',
    created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by            VARCHAR(64) NOT NULL DEFAULT '',
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by            VARCHAR(64) NOT NULL DEFAULT '',
    version_no            BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT uq_t_ztna_node_code UNIQUE (node_code),
    CONSTRAINT ck_t_ztna_node_type CHECK (node_type IN ('client_agent', 'gateway', 'relay', 'connector')),
    CONSTRAINT ck_t_ztna_node_status CHECK (node_status IN ('pending', 'active', 'disabled', 'quarantined', 'revoked')),
    CONSTRAINT ck_t_ztna_node_health CHECK (health_status IN ('unknown', 'healthy', 'degraded', 'unhealthy')),
    CONSTRAINT ck_t_ztna_node_config_versions CHECK (last_config_version >= 0 AND actual_config_version >= 0),
    CONSTRAINT ck_t_ztna_node_capabilities CHECK (jsonb_typeof(capabilities_json) = 'object'),
    CONSTRAINT ck_t_ztna_node_version CHECK (version_no > 0)
);

CREATE UNIQUE INDEX uq_t_ztna_node_public_key
    ON public.t_ztna_node (public_key) WHERE public_key IS NOT NULL;
CREATE INDEX ix_t_ztna_node_status_health
    ON public.t_ztna_node (node_status, health_status);
CREATE INDEX ix_t_ztna_node_heartbeat
    ON public.t_ztna_node (last_heartbeat_at DESC);

-- Nodes may attach to multiple routed networks; this relation is the source of
-- truth instead of duplicating a single network_id on t_ztna_node.
CREATE TABLE public.t_ztna_node_network (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id     BIGINT NOT NULL,
    network_id  BIGINT NOT NULL,
    role        VARCHAR(24) NOT NULL DEFAULT 'attached',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_t_ztna_node_network UNIQUE (node_id, network_id),
    CONSTRAINT fk_t_ztna_node_network_node FOREIGN KEY (node_id)
        REFERENCES public.t_ztna_node (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_node_network_network FOREIGN KEY (network_id)
        REFERENCES public.t_ztna_network (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_ztna_node_network_role CHECK (role IN ('primary', 'attached', 'route_gateway'))
);

CREATE INDEX ix_t_ztna_node_network_network
    ON public.t_ztna_node_network (network_id, node_id);
CREATE UNIQUE INDEX uq_t_ztna_node_network_primary
    ON public.t_ztna_node_network (node_id) WHERE role = 'primary';

CREATE TABLE public.t_ztna_node_endpoint (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id           BIGINT NOT NULL,
    endpoint_type     VARCHAR(24) NOT NULL,
    address           VARCHAR(255) NOT NULL,
    port              INTEGER NOT NULL,
    priority          INTEGER NOT NULL DEFAULT 100,
    last_verified_at  TIMESTAMPTZ,
    status            VARCHAR(16) NOT NULL DEFAULT 'unverified',
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_t_ztna_node_endpoint UNIQUE (node_id, endpoint_type, address, port),
    CONSTRAINT fk_t_ztna_node_endpoint_node FOREIGN KEY (node_id)
        REFERENCES public.t_ztna_node (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_ztna_node_endpoint_type CHECK (endpoint_type IN ('control', 'public', 'private', 'relay')),
    CONSTRAINT ck_t_ztna_node_endpoint_port CHECK (port BETWEEN 1 AND 65535),
    CONSTRAINT ck_t_ztna_node_endpoint_priority CHECK (priority >= 0),
    CONSTRAINT ck_t_ztna_node_endpoint_status CHECK (status IN ('unverified', 'active', 'disabled', 'unreachable'))
);

CREATE INDEX ix_t_ztna_node_endpoint_priority
    ON public.t_ztna_node_endpoint (node_id, status, priority);

CREATE TABLE public.t_ztna_protected_resource (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_name     VARCHAR(128) NOT NULL,
    resource_code     VARCHAR(64) NOT NULL,
    resource_type     VARCHAR(32) NOT NULL,
    network_id        BIGINT,
    host              VARCHAR(255),
    address           VARCHAR(255),
    port_start        INTEGER,
    port_end          INTEGER,
    protocol          VARCHAR(16),
    access_mode       VARCHAR(32) NOT NULL DEFAULT 'network',
    gateway_node_id   BIGINT,
    category          VARCHAR(64),
    tags_json         JSONB NOT NULL DEFAULT '[]'::JSONB,
    description       VARCHAR(512),
    status            VARCHAR(24) NOT NULL DEFAULT 'active',
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by        VARCHAR(64) NOT NULL DEFAULT '',
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by        VARCHAR(64) NOT NULL DEFAULT '',
    version_no        BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT uq_t_ztna_protected_resource_code UNIQUE (resource_code),
    CONSTRAINT fk_t_ztna_protected_resource_network FOREIGN KEY (network_id)
        REFERENCES public.t_ztna_network (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_protected_resource_gateway FOREIGN KEY (gateway_node_id)
        REFERENCES public.t_ztna_node (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_ztna_protected_resource_type CHECK (resource_type IN ('web_app', 'server', 'database', 'subnet', 'service')),
    CONSTRAINT ck_t_ztna_protected_resource_endpoint CHECK (host IS NOT NULL OR address IS NOT NULL),
    CONSTRAINT ck_t_ztna_protected_resource_ports CHECK (
        (port_start IS NULL AND port_end IS NULL)
        OR (port_start BETWEEN 1 AND 65535 AND port_end BETWEEN port_start AND 65535)
    ),
    CONSTRAINT ck_t_ztna_protected_resource_protocol CHECK (protocol IS NULL OR protocol IN ('tcp', 'udp', 'http', 'https')),
    CONSTRAINT ck_t_ztna_protected_resource_access_mode CHECK (access_mode IN ('network', 'proxy')),
    CONSTRAINT ck_t_ztna_protected_resource_tags CHECK (jsonb_typeof(tags_json) IN ('array', 'object')),
    CONSTRAINT ck_t_ztna_protected_resource_status CHECK (status IN ('active', 'disabled', 'unreachable')),
    CONSTRAINT ck_t_ztna_protected_resource_version CHECK (version_no > 0)
);

CREATE INDEX ix_t_ztna_protected_resource_network_status
    ON public.t_ztna_protected_resource (network_id, status);
CREATE INDEX ix_t_ztna_protected_resource_type_status
    ON public.t_ztna_protected_resource (resource_type, status);
CREATE INDEX ix_t_ztna_protected_resource_gateway
    ON public.t_ztna_protected_resource (gateway_node_id, status);

-- ---------------------------------------------------------------------------
-- Access policies and authorization records
