CREATE TABLE public.t_ztna_access_policy (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_name         VARCHAR(128) NOT NULL,
    policy_code         VARCHAR(64) NOT NULL,
    description         VARCHAR(512),
    priority            INTEGER NOT NULL DEFAULT 100,
    status              VARCHAR(24) NOT NULL DEFAULT 'draft',
    current_revision_id BIGINT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by          VARCHAR(64) NOT NULL DEFAULT '',
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by          VARCHAR(64) NOT NULL DEFAULT '',
    version_no          BIGINT NOT NULL DEFAULT 1,
    CONSTRAINT uq_t_ztna_access_policy_code UNIQUE (policy_code),
    CONSTRAINT ck_t_ztna_access_policy_status CHECK (status IN ('draft', 'active', 'disabled')),
    CONSTRAINT ck_t_ztna_access_policy_priority CHECK (priority >= 0),
    CONSTRAINT ck_t_ztna_access_policy_active_revision CHECK (status <> 'active' OR current_revision_id IS NOT NULL),
    CONSTRAINT ck_t_ztna_access_policy_version CHECK (version_no > 0)
);

CREATE INDEX ix_t_ztna_access_policy_status_priority
    ON public.t_ztna_access_policy (status, priority, id);
CREATE INDEX ix_t_ztna_access_policy_current_revision
    ON public.t_ztna_access_policy (current_revision_id);

CREATE TABLE public.t_ztna_access_policy_revision (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id      BIGINT NOT NULL,
    revision_no    BIGINT NOT NULL,
    rules_json     JSONB NOT NULL,
    compiled_hash  VARCHAR(128),
    change_summary VARCHAR(512),
    status         VARCHAR(24) NOT NULL DEFAULT 'draft',
    published_at   TIMESTAMPTZ,
    published_by   VARCHAR(64),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by     VARCHAR(64) NOT NULL DEFAULT '',
    CONSTRAINT uq_t_ztna_access_policy_revision UNIQUE (policy_id, revision_no),
    CONSTRAINT uq_t_ztna_access_policy_revision_policy_id UNIQUE (policy_id, id),
    CONSTRAINT fk_t_ztna_access_policy_revision_policy FOREIGN KEY (policy_id)
        REFERENCES public.t_ztna_access_policy (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_ztna_access_policy_revision_no CHECK (revision_no > 0),
    CONSTRAINT ck_t_ztna_access_policy_revision_rules CHECK (jsonb_typeof(rules_json) IN ('array', 'object')),
    CONSTRAINT ck_t_ztna_access_policy_revision_status CHECK (status IN ('draft', 'published', 'withdrawn')),
    CONSTRAINT ck_t_ztna_access_policy_revision_published CHECK (status <> 'published' OR published_at IS NOT NULL)
);

ALTER TABLE public.t_ztna_access_policy
    ADD CONSTRAINT fk_t_ztna_access_policy_current_revision
    FOREIGN KEY (id, current_revision_id)
    REFERENCES public.t_ztna_access_policy_revision (policy_id, id)
    DEFERRABLE INITIALLY DEFERRED;

CREATE INDEX ix_t_ztna_access_policy_revision_created
    ON public.t_ztna_access_policy_revision (policy_id, created_at DESC);

CREATE TABLE public.t_ztna_policy_subject (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id     BIGINT NOT NULL,
    subject_type  VARCHAR(16) NOT NULL,
    subject_id    BIGINT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_t_ztna_policy_subject UNIQUE (policy_id, subject_type, subject_id),
    CONSTRAINT fk_t_ztna_policy_subject_policy FOREIGN KEY (policy_id)
        REFERENCES public.t_ztna_access_policy (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_ztna_policy_subject_type CHECK (subject_type IN ('user', 'group', 'role', 'device')),
    CONSTRAINT ck_t_ztna_policy_subject_id CHECK (subject_id > 0)
);

CREATE INDEX ix_t_ztna_policy_subject_lookup
    ON public.t_ztna_policy_subject (subject_type, subject_id, policy_id);

CREATE TABLE public.t_ztna_policy_resource (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id             BIGINT NOT NULL,
    protected_resource_id BIGINT NOT NULL,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_t_ztna_policy_resource UNIQUE (policy_id, protected_resource_id),
    CONSTRAINT fk_t_ztna_policy_resource_policy FOREIGN KEY (policy_id)
        REFERENCES public.t_ztna_access_policy (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_policy_resource_resource FOREIGN KEY (protected_resource_id)
        REFERENCES public.t_ztna_protected_resource (id) ON DELETE RESTRICT
);

CREATE INDEX ix_t_ztna_policy_resource_resource
    ON public.t_ztna_policy_resource (protected_resource_id, policy_id);

CREATE TABLE public.t_ztna_authorization_decision (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    decision_id           VARCHAR(64) NOT NULL,
    user_id               BIGINT,
    device_id             BIGINT,
    protected_resource_id BIGINT,
    policy_id             BIGINT,
    policy_revision_id    BIGINT,
    decision              VARCHAR(16) NOT NULL,
    reason_code           VARCHAR(128) NOT NULL,
    auth_level            VARCHAR(32),
    device_trust_status   VARCHAR(24),
    source_ip             INET,
    request_id            VARCHAR(64),
    decided_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_t_ztna_authorization_decision_id UNIQUE (decision_id),
    CONSTRAINT fk_t_ztna_authorization_decision_user FOREIGN KEY (user_id)
        REFERENCES public.t_iam_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_authorization_decision_device FOREIGN KEY (device_id)
        REFERENCES public.t_ztna_device (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_authorization_decision_resource FOREIGN KEY (protected_resource_id)
        REFERENCES public.t_ztna_protected_resource (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_authorization_decision_policy FOREIGN KEY (policy_id)
        REFERENCES public.t_ztna_access_policy (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_authorization_decision_revision FOREIGN KEY (policy_id, policy_revision_id)
        REFERENCES public.t_ztna_access_policy_revision (policy_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_ztna_authorization_decision_result CHECK (decision IN ('allow', 'deny', 'step_up')),
    CONSTRAINT ck_t_ztna_authorization_decision_policy_revision CHECK ((policy_id IS NULL) = (policy_revision_id IS NULL)),
    CONSTRAINT ck_t_ztna_authorization_decision_trust CHECK (
        device_trust_status IS NULL OR device_trust_status IN ('unknown', 'trusted', 'untrusted', 'review_required')
    )
);

CREATE INDEX ix_t_ztna_authorization_decision_user_time
    ON public.t_ztna_authorization_decision (user_id, decided_at DESC);
CREATE INDEX ix_t_ztna_authorization_decision_resource_time
    ON public.t_ztna_authorization_decision (protected_resource_id, decided_at DESC);
CREATE INDEX ix_t_ztna_authorization_decision_result_time
    ON public.t_ztna_authorization_decision (decision, decided_at DESC);
CREATE INDEX ix_t_ztna_authorization_decision_request
    ON public.t_ztna_authorization_decision (request_id) WHERE request_id IS NOT NULL;

CREATE TABLE public.t_ztna_authorization_grant (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grant_id              VARCHAR(64) NOT NULL,
    user_id               BIGINT NOT NULL,
    device_id             BIGINT,
    protected_resource_id BIGINT NOT NULL,
    requested_by          BIGINT NOT NULL,
    approved_by           BIGINT,
    reason                VARCHAR(1024) NOT NULL,
    status                VARCHAR(24) NOT NULL DEFAULT 'requested',
    valid_from            TIMESTAMPTZ,
    expires_at            TIMESTAMPTZ,
    revoked_at            TIMESTAMPTZ,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_t_ztna_authorization_grant_id UNIQUE (grant_id),
    CONSTRAINT fk_t_ztna_authorization_grant_user FOREIGN KEY (user_id)
        REFERENCES public.t_iam_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_authorization_grant_device FOREIGN KEY (device_id)
        REFERENCES public.t_ztna_device (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_authorization_grant_resource FOREIGN KEY (protected_resource_id)
        REFERENCES public.t_ztna_protected_resource (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_authorization_grant_requester FOREIGN KEY (requested_by)
        REFERENCES public.t_iam_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_t_ztna_authorization_grant_approver FOREIGN KEY (approved_by)
        REFERENCES public.t_iam_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_t_ztna_authorization_grant_status CHECK (status IN ('requested', 'approved', 'rejected', 'revoked', 'expired')),
    CONSTRAINT ck_t_ztna_authorization_grant_window CHECK (
        (valid_from IS NULL AND expires_at IS NULL)
        OR (valid_from IS NOT NULL AND expires_at IS NOT NULL AND expires_at > valid_from)
    ),
    CONSTRAINT ck_t_ztna_authorization_grant_approval CHECK (status <> 'approved' OR (approved_by IS NOT NULL AND valid_from IS NOT NULL AND expires_at IS NOT NULL)),
    CONSTRAINT ck_t_ztna_authorization_grant_revoked CHECK ((status = 'revoked') = (revoked_at IS NOT NULL))
);

CREATE INDEX ix_t_ztna_authorization_grant_user_status
    ON public.t_ztna_authorization_grant (user_id, status, expires_at);
CREATE INDEX ix_t_ztna_authorization_grant_resource_status
    ON public.t_ztna_authorization_grant (protected_resource_id, status, expires_at);

