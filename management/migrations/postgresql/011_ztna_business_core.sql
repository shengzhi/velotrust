CREATE INDEX ix_t_ztna_tunnel_network_status
    ON public.t_ztna_tunnel (network_id, status);

CREATE TABLE public.t_ztna_tunnel_peer (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tunnel_id               BIGINT NOT NULL,
    node_id                 BIGINT NOT NULL,
    device_id               BIGINT,
    public_key              VARCHAR(64) NOT NULL,
    tunnel_ip               CIDR NOT NULL,
    allowed_ips             JSONB NOT NULL DEFAULT '[]'::JSONB,
    endpoint                VARCHAR(255),
    persistent_keepalive    INTEGER NOT NULL DEFAULT 0,
    status                  VARCHAR(24) NOT NULL DEFAULT 'pending',
    key_version             INTEGER NOT NULL DEFAULT 1,
    last_handshake_at       TIMESTAMPTZ,
    last_seen_at            TIMESTAMPTZ,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by              VARCHAR(64) NOT NULL DEFAULT '',
